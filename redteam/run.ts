#!/usr/bin/env node
/**
 * Red-team runner. Every case feeds an attack to the real SDIQT code from
 * committed fixtures, offline, and passes only when the code refuses it with
 * the expected reason while accepting the untampered input.
 *
 *   node redteam/run.ts           run, print one line per attempt, write RESULTS.md
 *   node redteam/run.ts --check   run, and fail if RESULTS.md is not what this run writes
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { rdkControl, swappedChunk, tamperedBundle, wrongVkey } from "./cases/bundle.ts";
import { ACCEPTED, type Case, ROOT, sha256Hex } from "./cases/common.ts";
import { staleExit } from "./cases/exit.ts";
import { replayedQstr } from "./cases/qstr.ts";
import { forgedReceipt } from "./cases/receipt.ts";

const RESULTS = join(ROOT, "redteam/RESULTS.md");
const FIXTURES = [
  "vectors/bundles/golden-v328/manifest.json",
  "vectors/bundles/golden-v328/chunk-0.bin",
  "vectors/bundles/golden-v328/chunk-1.bin",
  "vectors/bundles/golden-v328/chunk-2.bin",
  "vectors/bundles/rdk-v328-e2e/batch-1-FACE91C06DA7/manifest.json",
  "vectors/bundles/rdk-v328-e2e/batch-1-FACE91C06DA7/chunk-0.bin",
  "vectors/bundles/rdk-v328-e2e/batch-1-FACE91C06DA7/chunk-1.bin",
  "vectors/qstr/golden-v328.hex",
  "vectors/archive/rdk-v328-e2e-mwd5v89d/batches.jsonl",
  "redteam/fixtures/receipt-batch-3.json",
  "redteam/fixtures/tower-key.json",
];

const started = performance.now();
const cases: Case[] = [
  tamperedBundle(),
  swappedChunk(),
  wrongVkey(),
  replayedQstr(),
  forgedReceipt(),
  await staleExit(),
];
const liveProgram = rdkControl();

let failures = 0;
const fail = (line: string) => {
  failures += 1;
  console.log(`FAIL ${line}`);
};

for (const c of cases) {
  console.log(`\n[${c.id}] ${c.title}`);
  if (c.control.got.startsWith(ACCEPTED))
    console.log(`  ok   control accepted: ${c.control.input}`);
  else fail(`  control refused: ${c.control.input}: ${c.control.got}`);
  c.attempts.forEach((a, i) => {
    const id = `${c.id}${String.fromCharCode(97 + i)}`;
    const line = `${id} ${a.attack}\n       expect ${a.expect.source}\n       got    ${a.got}`;
    if (a.got.startsWith(ACCEPTED)) fail(`  ${line}\n       NOT REFUSED`);
    else if (!a.expect.test(a.got)) fail(`  ${line}\n       refused for another reason`);
    else console.log(`  ok   ${line}`);
  });
}
if (!liveProgram.startsWith(ACCEPTED)) fail(`live-program control refused: ${liveProgram}`);

function report(): string {
  const out = [
    "# Red-team results",
    "",
    "Generated by `node redteam/run.ts` from the fixtures below; do not edit by hand.",
    "Every attempt runs against the real code named in its case. A case passes when the",
    "untampered control is accepted and every attempt is refused with the expected reason.",
    "",
    `Result: ${failures === 0 ? "all refused" : `${failures} FAILED`}, ${cases.reduce((n, c) => n + c.attempts.length, 0)} attempts in ${cases.length} cases.`,
    "",
    "## Fixtures",
    "",
    "| File | SHA-256 |",
    "| --- | --- |",
    ...FIXTURES.map((f) => `| \`${f}\` | \`${sha256Hex(readFileSync(join(ROOT, f)))}\` |`),
    "",
  ];
  for (const c of cases) {
    out.push(`## ${c.id}. ${c.title}`, "");
    out.push(`Code: ${c.code.map((x) => `\`${x}\``).join("; ")}`, "");
    out.push(`Control: ${c.control.input}: **${c.control.got}**`, "");
    out.push("| # | Attack | Expected refusal | Actual |", "| --- | --- | --- | --- |");
    c.attempts.forEach((a, i) => {
      const cell = (s: string) => s.replaceAll("|", "\\|");
      const ok = !a.got.startsWith(ACCEPTED) && a.expect.test(a.got);
      out.push(
        `| ${c.id}${String.fromCharCode(97 + i)} | ${cell(a.attack)} | \`${cell(a.expect.source)}\` | ${ok ? "refused" : "**FAILED**"}: \`${cell(a.got)}\` |`,
      );
    });
    out.push("");
  }
  return out.join("\n");
}

const text = report();
const elapsed = ((performance.now() - started) / 1000).toFixed(1);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(RESULTS, "utf8");
  } catch {}
  if (current !== text) fail("redteam/RESULTS.md is out of date: run `node redteam/run.ts`");
} else {
  writeFileSync(RESULTS, text);
  console.log(`\nwrote ${RESULTS}`);
}
console.log(
  `\n${failures === 0 ? "all refused" : `${failures} failed`} (wall time ${elapsed} s, not recorded)`,
);
process.exitCode = failures === 0 ? 0 : 1;
