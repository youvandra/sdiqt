/**
 * QoreChain's own explorer. It picks the network from a cookie and opens on
 * mainnet, so a diana link shows "not found" until the visitor switches it to
 * Testnet once; CHAIN_NOTE says so next to the links.
 */
export const CHAIN_EXPLORER = "https://explore.qore.network";
export const txUrl = (hash: string) => `${CHAIN_EXPLORER}/tx/${hash.toUpperCase()}`;
export const blockUrl = (height: string | number) => `${CHAIN_EXPLORER}/block/${height}`;
/** Only bech32 chain accounts have an explorer page; other issuer ids return undefined. */
export const addressUrl = (addr: string) =>
  /^qor1[0-9a-z]{38,}$/.test(addr) ? `${CHAIN_EXPLORER}/address/${addr}` : undefined;
